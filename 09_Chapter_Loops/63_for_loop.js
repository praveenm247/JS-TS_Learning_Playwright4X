//for loop helps execute repeated statements/task
/*structure is:
for(Initialization; Condition; Increment/Updation)
{
   Statements;
}
*/

for (let i = 0; i < 10; i++)
{
    console.log(i);
}

for (let j = 0; j <= 10; ++j)
{
    console.log(j);
}

for (let k = 10; k > 0; k--)
{
    console.log(k);
}
