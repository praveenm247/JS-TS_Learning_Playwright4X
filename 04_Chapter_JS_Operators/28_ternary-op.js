/* Ternary operator is a shorthand for if-else statement. 
It takes three operands: condition ? expressionIfTrue : expressionIfFalse */
let age = 20;
let canVote = (age >= 18) ? "Yes, you can vote." : "No, you cannot vote.";
console.log(canVote); // This line logs the result of the ternary operation to the console, which will be "Yes, you can vote." since age is 20. 