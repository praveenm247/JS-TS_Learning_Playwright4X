// && -> AND Gate
// || -> OR Gate
// ! -> NOT Gate

let a = true;
let b = false;

console.log(a && b); // false - because both a and b are not true
console.log(a || b); // true - because at least one of a or b is true
console.log(!a); // false - because a is true, so !a is false
console.log(!b); // true - because b is false, so !b is true